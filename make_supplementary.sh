#!/usr/bin/env bash
# Build the anonymous supplementary zip for ARR from the committed tree.
# usage: SUPP_IDENT_REGEX='<account>|<surname>|<e-mail>|...' ./make_supplementary.sh out.zip
# The committed results/ir/draw_records.tar.xz contains the 226 retrieval input CSVs (~28 MB compressed).
# Verify its checksum and scan its contents before including it in the supplementary archive.
# Excludes: .git, the internal design log (docs/), the paper sources (submitted separately).
# Prints every file that still matches an identifying pattern; the expected answer is "none".
set -euo pipefail
OUT=$(python3 -c 'from pathlib import Path; import sys; print(Path(sys.argv[1]).resolve())' "${1:-supplementary.zip}")
: "${SUPP_IDENT_REGEX:?set SUPP_IDENT_REGEX to the identifying strings (account, names, e-mail)}"
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
git archive --format=tar HEAD | tar -x -C "$TMP"
rm -rf "$TMP/docs" "$TMP/paper" "$TMP/submission" "$TMP/make_supplementary.sh"
# size: per-draw records of the exploratory 30-decision runs are regenerated by code/RUN_PAIRS_MTME.sh; their summaries
# (results/DECISIONS*.csv) are kept
rm -f "$TMP"/results/mt/*_pairmtme*_draws.parquet "$TMP"/results/mt/*_pairmtme*_pred.parquet
IR_DRAWS_SHA256=a7ff90c7a6d33f117f502bb9170f450bf4d581f98d71676cbee1ab2c9810baff
echo "$IR_DRAWS_SHA256  $TMP/results/ir/draw_records.tar.xz" | sha256sum -c -
# The identifying-string check below also scans inside the compressed records.
mkdir -p "$TMP/.irscan" && tar -xJf "$TMP/results/ir/draw_records.tar.xz" -C "$TMP/.irscan"
cat > "$TMP/ANONYMITY_NOTE.md" <<'EOF'
This archive is the anonymised research artifact. Commit identifiers in prereg/LOCK_HISTORY.md refer to the
version-controlled repository, which will be made public after review; the timing record they document is self-reported.
Pools and judge outputs are not redistributed (see README, "Data").
EOF
HITS=$(grep -rIl -i -E "$SUPP_IDENT_REGEX" "$TMP" || true)
echo "files with identifying strings: ${HITS:-none}"
rm -rf "$TMP/.irscan"
(cd "$TMP" && zip -qr "$OUT" .)
du -h "$OUT"
